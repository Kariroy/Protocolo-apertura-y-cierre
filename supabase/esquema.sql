-- ============ Protocolos ============

-- Ítems editables de cada checklist (proto = 'apertura' | 'cierre').
create table public.protocolos_items (
  id bigint generated always as identity not null,
  proto text not null,
  txt text not null,
  "position" integer not null default 0,
  constraint protocolos_items_pkey primary key (id)
);

-- Una fila por protocolo y día: ítems marcados (jsonb [{txt, done}]), notas del
-- turno, si se terminó y a qué hora. El Registro de Protocolos y el panel salen de acá.
create table public.protocolos_dia (
  id bigint generated always as identity not null,
  proto text not null,
  dia date not null,
  items jsonb not null default '[]'::jsonb,
  notas text,
  terminado boolean not null default false,
  updated_at timestamp with time zone not null default now(),
  terminado_at timestamp with time zone,
  constraint protocolos_dia_pkey primary key (id),
  constraint protocolos_dia_proto_dia_key unique (proto, dia)
);

-- Horario de cada protocolo (desde / hasta; null = sin límite).
create table public.protocolos_config (
  proto text not null,
  hasta time without time zone,
  updated_at timestamp with time zone not null default now(),
  desde time without time zone,
  constraint protocolos_config_pkey primary key (proto)
);


-- ============ Mise and Please ============

-- Ítems del swipe (editables en ⚙).
create table public.mise_items (
  id bigint generated always as identity not null,
  cat text not null,
  ctx text,
  txt text not null,
  "position" integer not null default 0,
  constraint mise_items_pkey primary key (id)
);

-- Lista de producción abierta, compartida en vivo. Se borra con "Volver a empezar".
-- tipo: 'produccion' | 'tarea' (null = se deduce comparando con mise_tareas).
create table public.mise_lista (
  id bigint generated always as identity not null,
  cat text not null,
  ctx text,
  txt text not null,
  done boolean not null default false,
  "position" integer not null default 0,
  created_at timestamp with time zone not null default now(),
  comment text,
  tipo text,
  constraint mise_lista_pkey primary key (id)
);

-- Tareas del día (limpieza, mantenimiento…), editables en ⚙ → Tareas del día.
-- dia: 'Todos los días' | 'Lunes' … 'Domingo'.
create table public.mise_tareas (
  id bigint generated by default as identity not null,
  cat text,
  txt text not null,
  dia text not null default 'Todos los días'::text,
  "position" integer not null default 0,
  constraint mise_tareas_pkey primary key (id)
);

-- Registro diario (lo llena solo el trigger de abajo; lo lee el panel).
create table public.mise_registros (
  fecha date not null,
  prod_total integer not null default 0,
  prod_hechas integer not null default 0,
  tareas_total integer not null default 0,
  tareas_hechas integer not null default 0,
  items jsonb not null default '[]'::jsonb,
  updated_at timestamp with time zone not null default now(),
  constraint mise_registros_pkey primary key (fecha)
);


-- ============ Stock y Pedidos ============

create table public.stock_items (
