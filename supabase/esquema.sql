-- Un registro (conteo) por día.
create table public.stock_registros (
  id bigint generated always as identity not null,
  fecha date not null default ((now() at time zone 'America/Montevideo'::text))::date,
  created_at timestamp with time zone not null default now(),
  constraint stock_registros_pkey primary key (id),
  constraint stock_registros_fecha_key unique (fecha)
);

-- Foto de cada ítem en ese conteo. contado = false → "sin anotar" (no se pide).
create table public.stock_registro_items (
  id bigint generated always as identity not null,
  registro_id bigint not null,
  categoria text,
  proveedor text,
  item text not null,
  paquete text,
  por_paquete numeric not null default 0,
  cantidad_minima numeric not null default 0,
  ideal numeric not null default 0,
  cantidad_actual numeric not null default 0,
  "position" integer not null default 0,
  contado boolean not null default false,
  constraint stock_registro_items_pkey primary key (id),
  constraint stock_registro_items_registro_id_fkey foreign key (registro_id)
    references public.stock_registros(id) on delete cascade
);


